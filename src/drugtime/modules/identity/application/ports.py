from datetime import date
from typing import Protocol
from uuid import UUID

from drugtime.modules.identity.domain.profile import ProfileRecord
from drugtime.modules.identity.domain.user import UserRecord


class AuthProvider(Protocol):
    """Supabase Auth: credentials live in Supabase, not public.users."""

    def login_with_password(self, *, email: str, password: str) -> dict: ...
    def request_otp(
        self, *, phone: str | None, email: str | None, create_user: bool = False
    ) -> None: ...
    def verify_otp(self, *, phone: str | None, email: str | None, token: str) -> dict: ...
    def update_email(self, user_id: UUID, email: str | None) -> None: ...
    def delete_account(self, user_id: UUID) -> None: ...


class UserRepository(Protocol):
    def get_profile(self, user_id: UUID) -> ProfileRecord | None: ...
    def get(self, user_id: UUID) -> UserRecord | None: ...
    def create_minimal(self, user_id: UUID, *, phone: str | None, email: str | None) -> None: ...
    def update_profile(
        self,
        user_id: UUID,
        *,
        full_name: str,
        date_of_birth: date,
        gender: str,
        email: str | None = None,
    ) -> None: ...
    def device_tokens(self, user_ids: list[UUID], platform: str) -> list[tuple[UUID, str]]: ...
    def erase(self, user_id: UUID) -> None: ...


# Repository bảo đảm ownership và thay token cũ/mới nguyên tử trong UoW của caller.
class DeviceTokens(Protocol):
    def register(self, uow, user_id: UUID, token: str, previous: str | None) -> None: ...
    def unregister(self, uow, user_id: UUID, token: str) -> None: ...
