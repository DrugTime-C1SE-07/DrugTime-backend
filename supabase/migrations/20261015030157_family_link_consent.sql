BEGIN;

CREATE TABLE public.family_link_consent_confirmations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    link_id bigint NOT NULL UNIQUE CHECK (link_id > 0),
    patient_user_id uuid NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
    family_user_id uuid NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
    purpose text NOT NULL CHECK (purpose = 'family_sharing'),
    document_version text NOT NULL CHECK (char_length(document_version) BETWEEN 1 AND 64),
    confirmed_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    CHECK (patient_user_id <> family_user_id)
);

-- Snapshot link_id deliberately has no FK: erasure may delete the link, never its evidence.
CREATE FUNCTION public.check_family_link_confirmation() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    PERFORM 1 FROM public.caregiver_links
    WHERE id = NEW.link_id AND patient_user_id = NEW.patient_user_id
      AND family_user_id = NEW.family_user_id AND status = 'pending'
    FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'confirmation requires the matching pending family link';
    END IF;
    NEW.confirmed_at := clock_timestamp();
    RETURN NEW;
END $$;
CREATE TRIGGER family_link_confirmation_pair
    BEFORE INSERT ON public.family_link_consent_confirmations
    FOR EACH ROW EXECUTE FUNCTION public.check_family_link_confirmation();

CREATE TABLE public.family_link_audit_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id uuid NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
    patient_user_id uuid REFERENCES public.users(id) ON DELETE RESTRICT,
    link_id bigint CHECK (link_id > 0),
    operation text NOT NULL CHECK (operation IN ('list_pending', 'approve', 'reject')),
    result text NOT NULL CHECK (result IN ('allowed', 'denied')),
    reason text CHECK (reason IN ('khong_co_quyen', 'consent_revoked')),
    recorded_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    CHECK ((result = 'denied' AND reason IS NOT NULL) OR
           (result = 'allowed' AND reason IS NULL)),
    CHECK (result <> 'allowed' OR patient_user_id IS NOT NULL),
    CHECK (result <> 'allowed' OR operation = 'list_pending' OR link_id IS NOT NULL)
);
CREATE INDEX family_link_audit_patient_time_idx
    ON public.family_link_audit_events (patient_user_id, recorded_at DESC);
CREATE INDEX family_link_audit_actor_time_idx
    ON public.family_link_audit_events (actor_user_id, recorded_at DESC);
CREATE INDEX caregiver_links_pending_patient_time_idx
    ON public.caregiver_links (patient_user_id, linked_at DESC, id DESC)
    WHERE status = 'pending';

ALTER TABLE public.family_link_consent_confirmations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.family_link_audit_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.family_link_consent_confirmations, public.family_link_audit_events
    FROM PUBLIC, anon, authenticated, service_role, api_role, worker_role;
REVOKE ALL ON SEQUENCE public.family_link_consent_confirmations_id_seq,
    public.family_link_audit_events_id_seq
    FROM PUBLIC, anon, authenticated, service_role, api_role, worker_role;
GRANT SELECT, INSERT ON public.family_link_consent_confirmations,
    public.family_link_audit_events TO api_role;
GRANT USAGE ON SEQUENCE public.family_link_consent_confirmations_id_seq,
    public.family_link_audit_events_id_seq TO api_role;
GRANT SELECT ON public.family_link_consent_confirmations TO worker_role;
CREATE POLICY family_confirmations_api_select ON public.family_link_consent_confirmations
    FOR SELECT TO api_role USING (true);
CREATE POLICY family_confirmations_api_insert ON public.family_link_consent_confirmations
    FOR INSERT TO api_role WITH CHECK (true);
CREATE POLICY family_confirmations_worker_select ON public.family_link_consent_confirmations
    FOR SELECT TO worker_role USING (true);
CREATE POLICY family_audit_api_select ON public.family_link_audit_events
    FOR SELECT TO api_role USING (true);
CREATE POLICY family_audit_api_insert ON public.family_link_audit_events
    FOR INSERT TO api_role WITH CHECK (true);

REVOKE UPDATE, DELETE, TRUNCATE ON public.family_link_consent_confirmations,
    public.family_link_audit_events
    FROM PUBLIC, anon, authenticated, service_role, api_role, worker_role;
CREATE FUNCTION public.forbid_family_link_history_mutation() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION '% is append-only', TG_TABLE_NAME;
END $$;
CREATE TRIGGER family_confirmations_append_only
    BEFORE UPDATE OR DELETE ON public.family_link_consent_confirmations
    FOR EACH ROW EXECUTE FUNCTION public.forbid_family_link_history_mutation();
CREATE TRIGGER family_confirmations_no_truncate
    BEFORE TRUNCATE ON public.family_link_consent_confirmations
    FOR EACH STATEMENT EXECUTE FUNCTION public.forbid_family_link_history_mutation();
CREATE TRIGGER family_audit_append_only
    BEFORE UPDATE OR DELETE ON public.family_link_audit_events
    FOR EACH ROW EXECUTE FUNCTION public.forbid_family_link_history_mutation();
CREATE TRIGGER family_audit_no_truncate
    BEFORE TRUNCATE ON public.family_link_audit_events
    FOR EACH STATEMENT EXECUTE FUNCTION public.forbid_family_link_history_mutation();

COMMIT;
